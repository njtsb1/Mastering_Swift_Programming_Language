// --- Theme Management ---
function setTheme(theme) {
    htmlElement.setAttribute('data-theme', theme);
    localStorage.setItem('theme', theme);
    
    const currentLang = langSelect.value;
    if (theme === 'dark') {
        themeIcon.textContent = '🌙';
        themeText.textContent = translations[currentLang]?.srLightText || translations['en'].srLightText;
    } else {
        themeIcon.textContent = '☀️';
        themeText.textContent = translations[currentLang]?.srDarkText || translations['en'].srDarkText;
    }
}

themeToggleBtn.addEventListener('click', () => {
    const currentTheme = htmlElement.getAttribute('data-theme');
    const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
    setTheme(newTheme);
});

// --- Language Management ---
function updateLanguage(lang) {
    if (!translations[lang]) return;
    
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });

    // Update dynamic image alts dynamically for screen readers
    document.querySelectorAll('#drivers-grid .card').forEach((card, index) => {
        const img = card.querySelector('img');
        if(img) img.alt = translations[lang][driversData[index].titleKey];
    });
    document.querySelectorAll('#foods-grid .card').forEach((card, index) => {
        const img = card.querySelector('img');
        if(img) img.alt = translations[lang][foodsData[index].titleKey];
    });

    const currentTheme = htmlElement.getAttribute('data-theme');
    themeText.textContent = currentTheme === 'dark' ? translations[lang].srLightText : translations[lang].srDarkText;
    
    localStorage.setItem('lang', lang);
    langSelect.value = lang;
}

langSelect.addEventListener('change', (e) => {
    updateLanguage(e.target.value);
});

// --- Initialization ---
document.addEventListener('DOMContentLoaded', () => {
// 1. Generate items into document flow
renderGalleries();
// 2. Initialize Theme (Default to Dark)
const savedTheme = localStorage.getItem('theme') || 'dark';
setTheme(savedTheme);
// 3. Initialize Language (Default to English)
const savedLang = localStorage.getItem('lang') || 'en';
updateLanguage(savedLang);
});
